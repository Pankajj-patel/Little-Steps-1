export function localizeActivitySummary<T extends ActivitySummary>(
  activity: T,
  locale: LocaleCode
): T {
  if (locale !== 'hi') return activity;
  const hi = HINDI_ACTIVITIES_BY_ID[activity.id];
  return {
    ...activity,
    domainName: localizeDomainName(activity.domainSlug, activity.domainName, locale),
    ageGroupLabel: localizeAgeGroupLabel(activity.ageGroupSlug, activity.ageGroupLabel, locale),
    ...(hi
      ? {
          title: hi.title,
          summary: hi.summary,
          materials: hi.materials,
          safetyNotes: hi.safetyNotes,
        }
      : {}),
  };
}

export function localizeActivityDetail(
  activity: ActivityDetail,
  locale: LocaleCode
): ActivityDetail {
  if (locale !== 'hi') return activity;
  const hi = HINDI_ACTIVITIES_BY_ID[activity.id];
  const base = localizeActivitySummary(activity, locale);
  if (!hi) return base;
  return {
    ...base,
    steps: activity.steps.map((step, idx) => {
      const hiStep = hi.steps[idx];
      if (!hiStep) return step;
      return {
        ...step,
        title: hiStep.title,
        instructionText: hiStep.instructionText,
        caregiverTip: hiStep.caregiverTip,
      };
    }),
  };
}

export function localizeActivityTitleById(
  activityId: string,
  fallbackTitle: string,
  locale: LocaleCode
): string {
  if (locale !== 'hi') return fallbackTitle;
  return HINDI_ACTIVITIES_BY_ID[activityId]?.title ?? fallbackTitle;
}

export function localizePlanTitleAndFocus(
  title: string,
  focusNote: string,
  dayNumber: number,
  locale: LocaleCode
): { title: string; focusNote: string } {
  if (locale !== 'hi') return { title, focusNote };
  const exact = PLAN_TITLE_HI[title];
  if (exact) return exact;
  return {
    title: title.replace(/^Day\s+(\d+)/i, `दिन ${dayNumber}`),
    focusNote,
  };
}

