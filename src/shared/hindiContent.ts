export function localizeParentingTip(
  tip: { title: string; body: string; focusArea: string },
  locale: LocaleCode
): { title: string; body: string; focusArea: string } {
  if (locale !== 'hi') return tip;
  const hay = `${tip.title} ${tip.body} ${tip.focusArea}`.toLowerCase();
  const matched =
    PARENTING_TIPS_HI.find((item) => hay.includes(item.match)) ?? PARENTING_TIPS_HI[0];
  return {
    focusArea: matched.focusArea,
    title: matched.title,
    body: matched.body,
  };
}

